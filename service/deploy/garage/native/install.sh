#!/usr/bin/env bash
#
# Install Garage on a dedicated Linux machine, without Docker.
#
#   ./install.sh              # asks for sudo if it can be used, otherwise installs for you
#   VERSION=v2.1.0 ./install.sh
#
# Why native rather than the container: on a machine whose only job is this, the container
# adds a runtime and a second layer of lifecycle for no benefit. Garage is one static binary,
# one config file and two directories -- a systemd unit is the whole difference.
#
# What it does, in the order that matters:
#   1. downloads the pinned release (musl build: no libc version to fight)
#   2. writes a config with fresh secrets, binding the S3 API to the LAN, the admin API and
#      the web endpoint to localhost (they can do more damage than a bucket read)
#   3. installs and starts a systemd unit -- system-wide when sudo is available without a
#      password, otherwise in your own user session, with a cron @reboot line instead of
#      lingering if the session manager refuses to keep it alive
#
# It does NOT assign the node a role or create the bucket: `bootstrap.sh` does that, because
# it is the one step with a fixed order (layout assign, apply, key, bucket, allow) and it
# should be visible rather than buried in an installer.
set -euo pipefail

VERSION="${VERSION:-v2.1.0}"
PORT_S3="${PORT_S3:-3900}"
# Optional: an existing mount for the data blocks, e.g. /srv/garage/data
OBJECTS_DIR="${OBJECTS_DIR:-}"

say() { printf '==> %s\n' "$*"; }
die() { printf '[x] %s\n' "$*" >&2; exit 1; }

arch="$(uname -m)"
case "$arch" in
  x86_64|amd64) triple="x86_64-unknown-linux-musl" ;;
  aarch64|arm64) triple="aarch64-unknown-linux-musl" ;;
  *) die "no release build for $arch (the project publishes x86_64 and aarch64 musl builds)" ;;
esac

if sudo -n true 2>/dev/null; then
  SCOPE=system
  BIN=/usr/local/bin/garage
  CONFIG=/etc/garage.toml
  DATA=/var/lib/garage
  UNIT=/etc/systemd/system/garage.service
else
  SCOPE=user
  BIN="$HOME/.local/bin/garage"
  CONFIG="$HOME/.config/garage/garage.toml"
  DATA="$HOME/garage"
  UNIT="$HOME/.config/systemd/user/garage.service"
  say "sudo needs a password here, so this is a user-level install"
fi

say "installing garage $VERSION ($triple) as a $SCOPE service"
# Where the blocks go: a dedicated mount when there is one, otherwise beside the metadata.
OBJECTS_DIR="${OBJECTS_DIR:-}"
if [ -z "$OBJECTS_DIR" ]; then
  OBJECTS_DIR="$DATA/data"
elif ! mountpoint -q "$OBJECTS_DIR"; then
  # The footgun this exists for: a disk that failed to mount leaves Garage writing to the
  # root filesystem, which fills up before anyone notices -- `nofail` in fstab makes that a
  # quiet outcome rather than a boot failure.
  printf '[!] %s is not a mountpoint: blocks would land on the root filesystem\n' \
    "$OBJECTS_DIR" >&2
fi

mkdir -p "$(dirname "$BIN")" "$(dirname "$CONFIG")" "$DATA/meta" "$OBJECTS_DIR" "$(dirname "$UNIT")"
chmod 700 "$DATA"

if [ ! -x "$BIN" ] || [ "$("$BIN" --version 2>/dev/null | awk '{print $2}')" != "${VERSION#v}" ]; then
  tmp="$(mktemp)"
  say "downloading"
  curl -fsSL "https://garagehq.deuxfleurs.fr/_releases/$VERSION/$triple/garage" -o "$tmp"
  [ -s "$tmp" ] || die "the download is empty"
  install -m 0755 "$tmp" "$BIN" 2>/dev/null || { cp "$tmp" "$BIN"; chmod 0755 "$BIN"; }
  rm -f "$tmp"
fi
"$BIN" --version

if [ ! -f "$CONFIG" ]; then
  say "writing $CONFIG (fresh secrets)"
  rpc="$(openssl rand -hex 32)"
  admin="$(openssl rand -hex 16)"
  cat >"$CONFIG" <<TOMLEOF
# Garage on a dedicated machine. Secrets below were generated by install.sh; they are what
# the garage binary and the archive client both read, so copy them rather than retyping them.
# (No backticks in this heredoc: it is unquoted so the paths expand, which means backticks
# would be command substitutions -- a comment mentioning "garage" in backticks got run.)
metadata_dir = "$DATA/meta"
# OBJECTS_DIR points at a dedicated disk when there is one (see setup-data-disk.sh). Blocks
# are what grow, so they belong off the root filesystem; the metadata stays with the service.
data_dir = "$OBJECTS_DIR"
db_engine = "lmdb"

# One machine, one copy. This is an archive: the serving deployment holds its own copy of
# every piece, and this is the second one, not the only one.
replication_factor = 1
consistency_mode = "consistent"

# LMDB can corrupt on an unclean shutdown; snapshots are the cheap recovery path. The block
# files need no such care -- they are immutable and named by their hash.
metadata_auto_snapshot_interval = "6h"

# Single node: no peers to talk to, so the RPC port stays on loopback.
rpc_bind_addr = "127.0.0.1:3901"
rpc_secret = "$rpc"

[s3_api]
s3_region = "garage"
# The LAN: this is the one port another machine has to reach.
api_bind_addr = "0.0.0.0:$PORT_S3"
root_domain = ".s3.garage.localhost"

[s3_web]
# Serves bucket contents as static websites with *no authentication*. Loopback only, and
# nothing is marked as a website, so it stays quiet.
bind_addr = "127.0.0.1:3902"
root_domain = ".web.garage.localhost"
index = "index.html"

[admin]
# Can create and delete keys, so it never listens on the LAN.
api_bind_addr = "127.0.0.1:3903"
admin_token = "$admin"
metrics_token = "$admin"
TOMLEOF
  chmod 600 "$CONFIG"
else
  say "keeping the existing $CONFIG"
fi

say "writing $UNIT"
if [ "$SCOPE" = system ]; then
  unit_user="User=$(id -un)"
  unit_install='[Install]
WantedBy=multi-user.target'
else
  unit_user=""
  unit_install='[Install]
WantedBy=default.target'
fi
cat >"$UNIT" <<UNITEOF
# Garage, as a $SCOPE service. Restarts on any exit; the daemon is idempotent.
[Unit]
Description=Garage S3 object store (note-seq archive)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
${unit_user}
# Global options come BEFORE the subcommand in garage v2. "garage server --config X"
# fails with "Found argument '--config' which wasn't expected".
ExecStart=$BIN --config $CONFIG server
Restart=always
RestartSec=2
# Enough time to flush metadata on a clean stop; SIGKILL is what damages LMDB.
TimeoutStopSec=60
# An unprivileged account needs nothing else: everything it touches is under its data dir.
NoNewPrivileges=yes
PrivateTmp=yes

$unit_install
UNITEOF

if [ "$SCOPE" = system ]; then
  sudo systemctl daemon-reload
  sudo systemctl enable --now garage
  sudo systemctl --no-pager --lines=0 status garage || true
else
  systemctl --user daemon-reload
  systemctl --user enable --now garage
  # Without lingering, a user service stops when the last session ends -- which over SSH is
  # the moment you disconnect. Enabling it needs no privilege for your own user on most
  # distros; if it is refused, a cron @reboot line is the fallback that needs no privilege
  # at all.
  if ! loginctl enable-linger "$(id -un)" 2>/dev/null; then
    if ! crontab -l 2>/dev/null | grep -qF "systemctl --user start garage"; then
      (crontab -l 2>/dev/null; echo "@reboot XDG_RUNTIME_DIR=/run/user/$(id -u) systemctl --user start garage") \
        | crontab -
      say "added a cron @reboot line (lingering was refused)"
    fi
  fi
  systemctl --user --no-pager --lines=0 status garage || true
fi

sleep 2
if "$BIN" -c "$CONFIG" status >/dev/null 2>&1; then
  say "Garage is up. Next: ./bootstrap.sh (layout, key and bucket)"
else
  die "Garage did not answer -- try: $BIN -c $CONFIG status"
fi
